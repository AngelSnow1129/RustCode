use std::collections::BTreeMap;

use crate::model::{ModuleInfo, ProjectKind, ProjectModel, WikiLang};
use crate::safe_name;

/// Resolve a module name to its on-disk file base name (no extension), keeping it
/// unique and free of `/` or `\` so it can never escape `Modules/`.
fn file_of(name_map: &BTreeMap<String, String>, n: &str) -> String {
    name_map.get(n).cloned().unwrap_or_else(|| safe_name(n))
}

/// All human-facing prose for a wiki page, in one language.
struct Labels {
    /// Suffix appended to the project title on the Home page, e.g. ` — Wiki`.
    home_title: &'static str,
    /// Suffix appended to the project title on the Architecture page.
    arch_title: &'static str,
    /// Auto-generation banner; contains a `{}` placeholder for the project kind.
    auto_gen: &'static str,
    /// `Modules` / `模块`.
    modules: &'static str,
    /// `Files` / `文件`.
    files: &'static str,
    /// `Lines of code` / `代码行数`.
    loc: &'static str,
    /// `Architecture` / `架构`.
    architecture: &'static str,
    /// Link line pointing at the dependency graph page.
    arch_link: &'static str,
    /// `Dependency edges` / `依赖边`.
    dep_edges: &'static str,
    /// `Languages` / `语言`.
    languages: &'static str,
    /// Shown when no internal dependencies are detected.
    no_deps: &'static str,
    /// Welcome line on the README index.
    welcome: &'static str,
    /// `Home` / `首页` (used as the README link label).
    home: &'static str,
    /// `Summary` / `摘要`.
    summary: &'static str,
    /// `Files` heading on a module page.
    files_h: &'static str,
    /// `Depends on` / `依赖于`.
    depends_on: &'static str,
    /// `Path` / `路径`.
    path: &'static str,
    /// `Type` / `类型`.
    type_l: &'static str,
    /// Colon used after bold labels (`：` in Chinese, `:` in English).
    colon: &'static str,
    /// Placeholder shown when no summary is available.
    placeholder: &'static str,
    /// Trailing "and N more files" note; contains a `{}` placeholder.
    more_files: &'static str,
}

fn labels(lang: WikiLang) -> &'static Labels {
    match lang {
        WikiLang::Zh => &ZH,
        WikiLang::En => &EN,
    }
}

